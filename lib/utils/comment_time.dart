/// MangaLib returns comment timestamps as UTC ISO strings. Showing them raw
/// makes every date three hours off for a Moscow reader, so comment surfaces
/// format them in the device timezone instead.
String formatCommentTimestamp(String raw) {
  final parsed = DateTime.tryParse(raw);
  if (parsed == null) return raw;
  final local = parsed.toLocal();
  final day = local.day.toString().padLeft(2, '0');
  final month = local.month.toString().padLeft(2, '0');
  final hour = local.hour.toString().padLeft(2, '0');
  final minute = local.minute.toString().padLeft(2, '0');
  return '$day.$month.${local.year} $hour:$minute';
}